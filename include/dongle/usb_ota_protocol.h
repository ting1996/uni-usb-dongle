#ifndef DONGLE_USB_OTA_PROTOCOL_H
#define DONGLE_USB_OTA_PROTOCOL_H

#include <stddef.h>
#include <stdint.h>

#define DONGLE_USB_OTA_HEADER_SIZE 16U
#define DONGLE_USB_OTA_MAX_PAYLOAD_SIZE 1024U
#define DONGLE_USB_OTA_RESPONSE_FLAG 0x80U

typedef enum {
    DONGLE_USB_OTA_CMD_BEGIN = 1U,
    DONGLE_USB_OTA_CMD_DATA = 2U,
    DONGLE_USB_OTA_CMD_FINISH = 3U,
    DONGLE_USB_OTA_CMD_ABORT = 4U,
    DONGLE_USB_OTA_CMD_GET_DEVICE_STATE = 0x10U,
    DONGLE_USB_OTA_CMD_SELECT_CONTROLLER = 0x11U,
    DONGLE_USB_OTA_CMD_REMOVE_CONTROLLER = 0x12U,
    DONGLE_USB_OTA_CMD_START_DISCOVERY = 0x13U,
    DONGLE_USB_OTA_CMD_PAIR_CONTROLLER = 0x14U,
    DONGLE_USB_OTA_CMD_TEST_GAMEPAD = 0x15U,
    DONGLE_USB_OTA_CMD_GET_GAMEPAD_DIAGNOSTICS = 0x16U,
    DONGLE_USB_OTA_CMD_DISCOVERY_RESULT = 0x17U,
    DONGLE_USB_OTA_CMD_RADIO_STATE = 0x18U,
    DONGLE_USB_OTA_CMD_PAIR_AUDIO = 0x19U,
    DONGLE_USB_OTA_CMD_DISCONNECT_PEER = 0x1aU,
    DONGLE_USB_OTA_CMD_CAPTURE_MEDIA = 0x1cU,
    DONGLE_USB_OTA_CMD_READ_MEDIA_CAPTURE = 0x1dU,
    DONGLE_USB_OTA_CMD_GET_PROFILE_STATE = 0x1eU,
    DONGLE_USB_OTA_CMD_SET_PROFILE = 0x1fU,
    DONGLE_USB_OTA_CMD_GET_AUDIO_METRICS = 0x20U,
    DONGLE_USB_OTA_CMD_GET_DUALSENSE_METRICS = 0x21U,
    DONGLE_USB_OTA_CMD_GET_MIC_CONFIG = 0x22U,
    DONGLE_USB_OTA_CMD_SET_MIC_SOURCE = 0x23U,
    DONGLE_USB_OTA_CMD_REMOVE_AUDIO = 0x24U,
    DONGLE_USB_OTA_CMD_GET_BLOCKLIST = 0x25U,
    DONGLE_USB_OTA_CMD_BLOCK_DEVICE = 0x26U,
    DONGLE_USB_OTA_CMD_UNBLOCK_DEVICE = 0x27U,
    DONGLE_USB_OTA_CMD_GET_RUMBLE_GAIN = 0x28U,
    DONGLE_USB_OTA_CMD_SET_RUMBLE_GAIN = 0x29U
} dongle_usb_ota_command_t;

typedef enum {
    DONGLE_MIC_SOURCE_AUTO = 0U,
    DONGLE_MIC_SOURCE_HEADPHONE = 1U,
    DONGLE_MIC_SOURCE_CONTROLLER_0 = 2U,
    DONGLE_MIC_SOURCE_CONTROLLER_1 = 3U,
    DONGLE_MIC_SOURCE_OFF = 4U,
    DONGLE_MIC_SOURCE_COUNT = 5U
} dongle_mic_source_t;

typedef enum {
    DONGLE_USB_OTA_STATUS_OK = 0U,
    DONGLE_USB_OTA_STATUS_INVALID_FRAME,
    DONGLE_USB_OTA_STATUS_INVALID_COMMAND,
    DONGLE_USB_OTA_STATUS_BUSY,
    DONGLE_USB_OTA_STATUS_INVALID_IMAGE,
    DONGLE_USB_OTA_STATUS_UPDATE_FAILED,
    DONGLE_USB_OTA_STATUS_BAD_OFFSET,
    DONGLE_USB_OTA_STATUS_INCOMPLETE,
    DONGLE_USB_OTA_STATUS_UNSUPPORTED,
    DONGLE_USB_OTA_STATUS_STORAGE_ERROR,
    DONGLE_USB_OTA_STATUS_NOT_FOUND
} dongle_usb_ota_status_t;

#define DONGLE_DEVICE_CAPABILITY_BT_HID 0x01U
#define DONGLE_DEVICE_CAPABILITY_USB_GAMEPAD 0x02U
#define DONGLE_DEVICE_CAPABILITY_AUDIO 0x04U

#define DONGLE_DEVICE_STATE_PAYLOAD_SIZE 21U
#define DONGLE_PROFILE_STATE_PAYLOAD_SIZE 12U
#define DONGLE_AUDIO_METRICS_PAYLOAD_SIZE 12U
#define DONGLE_DUALSENSE_METRICS_PAYLOAD_SIZE 38U
#define DONGLE_MIC_STATE_PAYLOAD_SIZE 16U
#define DONGLE_RUMBLE_GAIN_PAYLOAD_SIZE 3U
#define DONGLE_RUMBLE_GAIN_MAX 400U
#define DONGLE_BLOCKLIST_MAX_ENTRIES 6U
#define DONGLE_BLOCKLIST_MAX_PAYLOAD_SIZE (3U + DONGLE_BLOCKLIST_MAX_ENTRIES * 6U)

typedef enum {
    DONGLE_USB_OTA_PROTOCOL_OK = 0,
    DONGLE_USB_OTA_PROTOCOL_INVALID_ARGUMENT,
    DONGLE_USB_OTA_PROTOCOL_INVALID_FRAME,
    DONGLE_USB_OTA_PROTOCOL_UNSUPPORTED_VERSION,
    DONGLE_USB_OTA_PROTOCOL_PAYLOAD_TOO_LARGE,
    DONGLE_USB_OTA_PROTOCOL_CHECKSUM_MISMATCH
} dongle_usb_ota_protocol_result_t;

typedef struct {
    uint8_t command;
    uint32_t sequence;
    uint16_t payload_size;
    const uint8_t *payload;
} dongle_usb_ota_frame_t;

dongle_usb_ota_protocol_result_t dongle_usb_ota_encode(
    uint8_t *buffer,
    size_t buffer_size,
    uint8_t command,
    uint32_t sequence,
    const uint8_t *payload,
    uint16_t payload_size,
    size_t *encoded_size);

dongle_usb_ota_protocol_result_t dongle_usb_ota_decode(
    const uint8_t *buffer,
    size_t buffer_size,
    dongle_usb_ota_frame_t *frame);

#endif
